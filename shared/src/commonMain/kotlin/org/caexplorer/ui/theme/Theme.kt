/**
 * Available color palettes for the app UI.
 */
enum class AppPalette(val displayName: String) {
    FIRE("Fire"),
    OCEAN("Ocean"),
    FOREST("Forest"),
    VIOLET("Violet"),
    MONOCHROME("Monochrome"),
    PASTEL("Pastel"),
    BOB_ROSS("Bob Ross"),
    NEON("Neon"),
    CYBERPUNK("Cyberpunk"),
    SUPERCAR("Supercar");

    val colorScheme: ColorScheme
        get() = when (this) {
            FIRE -> FireDark
            OCEAN -> OceanDark
            FOREST -> ForestDark
            VIOLET -> VioletDark
            MONOCHROME -> MonochromeDark
            PASTEL -> PastelDark
            BOB_ROSS -> BobRossDark
            NEON -> NeonDark
            CYBERPUNK -> CyberpunkDark
            SUPERCAR -> SupercarDark
        }
}

